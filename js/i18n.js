function langue() {
  return localStorage.getItem("paris-game-lang") === "en" ? "en" : "fr";
}

function t(cle) {
  return (TEXTES[langue()] && TEXTES[langue()][cle]) || TEXTES.fr[cle] || cle;
}

function texte(valeur) {
  if (valeur && typeof valeur === "object") return valeur[langue()] || valeur.fr;
  return valeur;
}

function appliquerLangue(racine = document) {
  const code = langue();
  document.documentElement.lang = code;
  racine.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  racine.querySelectorAll("[data-i18n-src]").forEach((el) => {
    el.src = t(el.dataset.i18nSrc);
  });
  racine.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    el.alt = t(el.dataset.i18nAlt);
  });
  const page = document.body && document.body.dataset.page;
  if (page && TEXTES[code]["title." + page]) document.title = t("title." + page);
  const compte = document.querySelector(".account-link");
  if (compte) compte.setAttribute("aria-label", t("nav.account"));
  const panierLien = document.querySelector(".cart-link");
  if (panierLien) {
    const n = typeof totalArticles === "function" ? totalArticles() : 0;
    const nom = t("nav.cart");
    panierLien.setAttribute("aria-label", n > 0 ? `${nom} (${n})` : nom);
  }
  const menu = document.querySelector(".menu-btn");
  if (menu) menu.setAttribute("aria-label", t("nav.menu"));
  const bouton = document.querySelector(".lang-btn");
  if (bouton) {
    bouton.innerHTML = code === "en"
      ? `<svg class="flag" viewBox="0 0 60 30" aria-hidden="true"><rect width="60" height="30" fill="#012169"/><path d="M0 0L60 30M60 0L0 30" stroke="#fff" stroke-width="8"/><path d="M0 0L60 30M60 0L0 30" stroke="#C8102E" stroke-width="4"/><path d="M30 0V30M0 15H60" stroke="#fff" stroke-width="14"/><path d="M30 0V30M0 15H60" stroke="#C8102E" stroke-width="8"/></svg>`
      : `<svg class="flag" viewBox="0 0 3 2" aria-hidden="true"><rect width="1" height="2" fill="#0055a4"/><rect x="1" width="1" height="2" fill="#fff"/><rect x="2" width="1" height="2" fill="#ef4135"/></svg>`;
    bouton.setAttribute("aria-label", t("nav.lang"));
  }
}

function choisirLangue(code) {
  localStorage.setItem("paris-game-lang", code === "en" ? "en" : "fr");
  appliquerLangue();
  document.dispatchEvent(new Event("langue"));
}
